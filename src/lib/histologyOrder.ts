type NamedCard = { preparation?: { name?: string } | null };

export function emPlanRank(card: NamedCard): number {
  const name = String(card.preparation?.name || "").toLowerCase();
  const idx = EM_PLAN_ORDER.findIndex(([needle]) => name.includes(needle));
  return idx === -1 ? 9999 : idx;
}

export function sortEmCards<T extends NamedCard>(items: T[]): T[] {
  return [...items].sort(
    (a, b) =>
      emPlanRank(a) - emPlanRank(b) ||
      String(a.preparation?.name || "").localeCompare(String(b.preparation?.name || ""), "ru"),
  );
}

export function isElectronogramCard(card: { mode_set?: unknown; tags?: unknown }): boolean {
  const tags = Array.isArray(card.tags) ? card.tags.map((t) => String(t).toLowerCase()) : [];
  const mode = String(card.mode_set || "").toLowerCase();
  return tags.some((t) => t.includes("electron") || t.includes("электронограм")) || mode.includes("electron");
}

/** Ключ занятия для группировки: название темы плана, иначе первая метка. */
export function lessonKeyOf(card: { plan_topic_title?: unknown; plan_module_title?: unknown; tags?: unknown }): string {
  const t = String(card.plan_topic_title || "").trim();
  if (t) return t;
  const m = String(card.plan_module_title || "").trim();
  if (m) return m;
  const tags = Array.isArray(card.tags) ? card.tags.map(String) : [];
  return tags[0] || "Без темы";
}

/** Номер недели из названия занятия («Неделя 8–9 · …») для сортировки групп. */
export function planWeekNumber(title: string): number {
  const m = /неделя\s+(\d+)/i.exec(title);
  return m ? Number(m[1]) : 9999;
}

export function compareLessons(a: string, b: string): number {
  return planWeekNumber(a) - planWeekNumber(b) || a.localeCompare(b, "ru");
}
