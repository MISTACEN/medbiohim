**Ретикулоциты** — молодые формы, 1–5% эритроцитов. Содержат остатки рРНК, рибосом и митохондрий; при суправитальной окраске бриллиантовым крезиловым голубым они дают зернисто-сетчатую субстанцию.

## 3. Тромбоциты — Thrombocyti

Тромбоциты — **безъядерные фрагменты цитоплазмы мегакариоцитов** красного костного мозга. Диаметр 2–3 мкм.

