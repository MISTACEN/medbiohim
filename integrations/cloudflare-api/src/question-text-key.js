/**
 * Ключ сравнения формулировок вопросов — только для аудита контента.
 *
 * Импорт методичек приносит один и тот же вопрос дважды: разные id, одинаковый
 * текст, а отличаются они числом подчёркиваний в пропуске («_____» и «______»),
 * регистром первой буквы или точкой в конце. Такой ключ помогает найти такие
 * пары в банке.
 *
 * ВАЖНО: этим ключом нельзя фильтровать вопросы внутри попытки. В гистологии
 * 178 вопросов имеют одну и ту же формулировку «Какой препарат изображён на
 * фотографии?», тот же ответ и те же варианты — различает их только картинка,
 * которой нет в строке вопроса. Склейка по тексту выбросила бы 177 реальных
 * заданий, поэтому брак в данных чинится удалением копий, а не фильтром на лету.
 */
export function questionTextKey(text) {
  return String(text ?? "")
    .toLowerCase()
    .replace(/[^0-9a-zа-яё]+/g, " ")
    .trim();
}
