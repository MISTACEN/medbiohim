### Центральные органы
- **Гипофиз** связан с гипоталамусом; аденогипофиз содержит хромофильные и хромофобные клетки, нейрогипофиз — нервные волокна и питуициты.
- **Щитовидная железа** построена из фолликулов, заполненных коллоидом. Фолликулярные клетки синтезируют гормоны щитовидной железы; парафолликулярные C-клетки выделяют кальцитонин.
- **Надпочечник** имеет корковое и мозговое вещество. В коре различают клубочковую, пучковую и сетчатую зоны; мозговое вещество содержит хромаффинные клетки.

### Как отличать железы
У щитовидной железы ищите округлые фолликулы с однородным коллоидом. В гипофизе нет фолликулярной организации: аденогипофиз выглядит как клеточные тяжи вокруг синусоидных капилляров. В надпочечнике ориентируйтесь на зональное строение коры и более тёмные клеточные скопления мозгового вещества.

### Повторение
