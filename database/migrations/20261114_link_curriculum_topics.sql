-- 3. Физиология: связываем позиции по номеру из названия («Лек 12: …» → «Лекция 12 · …»,
--    «Практика 18: …» → «Практика 18 · …»). Без номера в названии соединение даёт перекрёстные пары.
UPDATE public.curriculum_items ci
SET topic_id = t.id, updated_at = now()
FROM public.topics t
JOIN public.modules m ON m.id = t.module_id
JOIN public.subjects s ON s.id = m.subject_id
WHERE s.slug = 'physiology'
  AND ci.subject_id = s.id
  AND ci.is_active
  AND ci.planned_date IS NOT NULL
  AND ci.title ~ '^Лек[[:space:]]*[0-9]+[[:space:]]*:'
  AND t.title LIKE 'Лекция ' || substring(ci.title from '[0-9]+') || ' · %';

