# Лекция №5. Кровь и лимфа

> **Навигация по лекции:** кровь → эритроциты → тромбоциты → лейкоциты → гемограмма → лейкоцитарная формула → возрастные перекрёсты → электронограмма эозинофила → 4-столбчатая карточка.

## 1. Кровь как ткань

**Кровь (sanguis, haima)** — жидкая ткань внутренней среды мезенхимного происхождения. Она состоит из плазмы и форменных элементов.

| Компонент | Доля |
|---|---:|
| Плазма | 55–60% |
| Форменные элементы | 40–45% |

| Функция | Смысл |
|---|---|
| Дыхательная | O₂ от лёгких к тканям, CO₂ к лёгким |
| Трофическая | доставка глюкозы, аминокислот, жиров |
| Защитная | иммунитет, фагоцитоз, свёртывание |
| Выделительная | перенос продуктов обмена к почкам |
| Гомеостатическая | постоянство внутренней среды, pH 7,36, осмотическое давление |
| Регуляторная | перенос гормонов и биологически активных веществ |

> **Опорная мысль:** кровь = транспорт + защита + поддержание гомеостаза.

