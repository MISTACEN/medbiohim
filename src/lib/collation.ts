/**
 * Единый компаратор для пользовательских списков.
 *
 * Системный `.sort()` ставит кириллицу в произвольном порядке, а разные экраны
 * передавали собственные опции `localeCompare`. Один компаратор держит порядок
 * одинаковым во всех каталогах: русская коллимация, числа по значению
 * («Тема 2» раньше «Тема 10»), регистр и «ё» не влияют на сравнение.
 */
export function compareRu(left: string, right: string): number {
  return left.localeCompare(right, "ru", { numeric: true, sensitivity: "base" });
}
