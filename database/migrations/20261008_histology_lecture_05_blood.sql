## 13. Мини-проверка

- 2 сегмента + крупные розовые гранулы → **эозинофил**
- 3–5 сегментов + мелкая бледная зернистость → **сегментоядерный нейтрофил**
- S / палочка / подкова без сегментов → **палочкоядерный нейтрофил**
- 18–20 мкм + бобовидное ядро + дымчатая цитоплазма → **моноцит**
- крупное тёмное ядро + узкий ободок → **лимфоцит**
- крупные тёмно-фиолетовые гранулы → **базофил**
- >9,0 × 10⁹/л → **лейкоцитоз**
- <4,0 × 10⁹/л → **лейкопения**
- >6% эозинофилов → **эозинофилия**
- >37% лимфоцитов у взрослого → **лимфоцитоз**
- увеличение палочкоядерных/юных → **сдвиг влево**

