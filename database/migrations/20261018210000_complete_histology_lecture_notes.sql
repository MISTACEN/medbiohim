### Нейроны
Нейрон состоит из тела (перикариона), дендритов и аксона. Дендриты обычно принимают сигналы, аксон проводит импульс от тела клетки к другим клеткам. По числу отростков различают мультиполярные, биполярные и псевдоуниполярные нейроны; по функции — чувствительные, вставочные и двигательные.

### Нейроглия
- **Астроциты** поддерживают нейронное микроокружение, участвуют в регуляции внеклеточных ионов и контактах с сосудами.
- **Олигодендроциты** образуют миелин в центральной нервной системе; в периферической системе миелин формируют шванновские клетки.
- **Микроглия** выполняет иммунный надзор и фагоцитоз.
- **Эпендимоциты** выстилают желудочки мозга и центральный канал спинного мозга; специализированные клетки участвуют в работе сосудистых сплетений.

### Нервные волокна и синапсы
Нервное волокно включает осевой цилиндр (аксон) и окружающие его оболочки. Миелин повышает скорость проведения; в периферическом волокне между миелиновыми сегментами расположены узлы Ранвье. В химическом синапсе сигнал передаётся через медиатор из пресинаптического окончания в синаптическую щель к рецепторам постсинаптической мембраны.

### Как распознавать препарат
Ищите тела нейронов, ядра и ядрышки, отростки, нейропиль и характер глии. В спинальном ганглии крупные псевдоуниполярные нейроны окружены клетками-сателлитами; в мозжечке различают молекулярный слой, слой клеток Пуркинье и зернистый слой.
