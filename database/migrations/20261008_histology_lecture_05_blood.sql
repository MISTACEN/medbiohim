## 8. Электронограмма: эозинофильный гранулоцит

**Алгоритм описания:**

1. **Название:** эозинофильный гранулоцит.
2. **Размер:** 12–14 мкм в мазке.
3. **Ядро:** 2 сегмента, «очки», тонкая перемычка; гетерохроматин под кариолеммой.
4. **Цитоплазма:** комплекс Гольджи, митохондрии, актиновые микрофиламенты, азурофильные и специфические гранулы.
5. **Специфические гранулы:** 0,5–1,5 мкм; электронно-плотный кристаллоидный центр + более светлый аморфный матрикс.
6. **Кристаллоид:** MBP и эозинофильный катионный белок.
7. **Матрикс:** гистаминаза, арилсульфатаза, кислая фосфатаза, пероксидаза.
8. **Рецепторы:** Fc-рецепторы к IgE/IgG/IgM; рецепторы C3/C4; рецепторы хемотаксиса к гистамину.

