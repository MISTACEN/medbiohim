### Моноциты — 3–11%

Самые крупные клетки крови: **18–20 мкм**. Ядро бобовидное, подковообразное или инвагинированное, хроматин рыхлый. Цитоплазма широкая, дымчатая, серо-голубая.

Это клетки мононуклеарной фагоцитарной системы. В крови находятся 36–104 часа, затем мигрируют в ткани и превращаются в тканевые макрофаги: гистиоциты, клетки Купфера, остеокласты, альвеолярные макрофаги.

