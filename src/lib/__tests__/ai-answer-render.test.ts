import { describe, expect, it } from "vitest";
import { mdToHtml } from "../lectures/markdown";

/**
 * Реальный ответ тьютора на вопрос про СОЭ и альбумин (скопирован из отчёта
 * студента). Проверяем, что в готовом HTML нет служебных следов модели:
 * съеденных тегов («3>…3>»), видимых звёздочек и повторённого абзаца.
 */
const ANSWER = [
  "**В ключе ошибка: ваш ответ вернее.**",
  "",
  "*Однако правильный ответ – уменьшение скорости оседания эритроцитов (СОЭ). Ваш вариант «увеличивается» противоречит физиологическому механизму, но всё‑же ближе к правильному, чем утверждение «не изменяется».*",
  "*Однако правильный ответ – уменьшение скорости оседания эритроцитов (СОЭ). Ваш вариант «увеличивается» противоречит физиологическому механизму, но всё‑же ближе к правильному, чем утверждение «не изменяется».*",
  "",
  "### Механизм влияния альбумина на СОЭ",
  "Рулет‑образование — основной фактор, ускоряющий оседание эритроцитов; вызывается притягательными силами между эритроцитами, усиливаемыми белками с положительным зарядом (фибриноген, иммуноглобулины).",
  "Альбумин — основной отрицательно заряженный плазменный белок; повышает репульсивные (отталкивающие) силы между эритроцитами.",
  "",
  "### Почему вариант «не изменяется» неверен",
  "В реальной физиологии даже небольшие изменения соотношения альбумин/фибриноген влияют на вязкость плазмы.",
  "",
  "| Плазменный белок | Влияние на СОЭ |",
  "| --- | --- |",
  "| Фибриноген, IgG/IgM | ↑ (усиливает рулет‑образование) |",
  "| Альбумин | ↓ (усиливает отталкивание) |",
  "",
  "### Мнемоника",
  "«Альбумин – Анти‑Рулет» – альбумин «против» образованию рулет‑кластера, следовательно, СОЭ падает.",
].join("\n");

describe("mdToHtml — живой ответ про СОЭ", () => {
  const html = mdToHtml(ANSWER);

  it("не оставляет съеденных тегов", () => {
    expect(html).not.toContain("3>Механизм влияния альбумина на СОЭ3>");
    expect(html).not.toMatch(/<h<sub>/);
    expect(html).toContain("<h3>Механизм влияния альбумина на СОЭ</h3>");
  });

  it("абзац после заголовка остаётся абзацем", () => {
    expect(html).not.toMatch(/<\/h3>\s*Рулет/);
    expect(html).toMatch(/<p>Рулет/);
  });

  it("не показывает звёздочки", () => {
    expect(html).not.toContain("*");
    expect(html).toContain("<em>");
    expect(html).toContain("<strong>В ключе ошибка");
  });

  it("не повторяет один и тот же абзац", () => {
    const repeats = html.match(/Однако правильный ответ/g) ?? [];
    expect(repeats.length).toBe(1);
  });

  it("сохраняет таблицу и заголовки блоком", () => {
    expect(html).toContain("lec-table");
    expect(html).not.toMatch(/<p>[^<]*<h3>/);
  });
});
