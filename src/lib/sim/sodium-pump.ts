/**
 * Na⁺/K⁺-АТФаза (натрий-калиевый насос) — обязательная модель задания §9.1.
 *
 * Цикл Поста–Альберса из 8 этапов: связывание 3 Na⁺ → АТФ → фосфорилирование →
 * E1-P→E2-P → выход 3 Na⁺ → связывание 2 K⁺ → дефосфорилирование → возврат
 * 2 K⁺ внутрь. Анимация цикла — компонент NaKPumpVisual (visual: "na-k-pump"),
 * текстовые этапы и проверка работают в общем плеере симуляций.
 *
 * Числа: стехиометрия 3Na⁺/2K⁺/1АТФ — установленный факт; зависимость от
 * калиемии — учебное упрощение (фактор Михаэлиса с K₀.₅ = 1 мМ);
 * электрогенный вклад масштабируется от ~8 мВ при физиологической калиемии —
 * это оценка, а не расчёт ёмкости мембраны.
 */

