### 7C. Гемограмма по ключевым возрастным периодам

**Новорождённый, 0–14 дней**
- Эритроциты: **6,0–7,0 × 10¹²/л**.
- Hb: **180–210 г/л**; HbF около **80%** в присланном материале.
- Лейкоциты: **10,0–30,0 × 10⁹/л**.
- Ретикулоциты: до **10%**.
- Возможны анизоцитоз, макроцитоз и единичные ядросодержащие предшественники эритроцитов.

**10–14 сутки**
- Эритроциты: **4,0–5,0 × 10¹²/л**.
- Лейкоциты: **9,0–15,0 × 10⁹/л**.
- Первый физиологический перекрёст указан для **4-х суток**.

**Грудной возраст, 3–6 месяцев**
- В присланном материале описана физиологическая анемия: разрушение эритроцитов с HbF и замещение его HbA.
- Эритроциты: **3,5–4,5 × 10¹²/л**.
- Hb: **110–130 г/л**.

**1–2 года**
- Лимфоциты: **60–65% (до 70%)**.
- Нейтрофилы: **20–30%**.

**4 года**
- Второй физиологический перекрёст: нейтрофилы и лимфоциты около **45%**.

**14–15 лет и взрослые**
- Эритроциты: мужчины **4,0–5,5 × 10¹²/л**, женщины **3,7–4,9 × 10¹²/л**; отдельно в присланном материале указана лекционная величина для женщин **3,9–4,7 × 10¹²/л**.
- Hb: мужчины **130–160 г/л**, женщины **120–140 г/л**.
- Лейкоциты: **4,0–9,0 × 10⁹/л**; отдельно указан вариант **4,5–9,0 × 10⁹/л**.
- Тромбоциты: **180–320 × 10⁹/л**; отдельно указан вариант **250–300 × 10⁹/л**.
- Ретикулоциты: **1–5%**.
- СОЭ: мужчины **4–8 мм/ч**, женщины **7–10 мм/ч**.

### 7D. Экспресс-алгоритм возрастной карточки

1. Сначала смотри возраст пациента.
2. Выбирай норму именно для этого возраста.
3. Сравнивай показатель с соответствующим возрастным столбцом.
4. Только после этого делай вывод о повышении/снижении.

