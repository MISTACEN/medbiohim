## Дополнительный конспект MEDBIOHIM: орофациальная гистология

Материал для самостоятельной подготовки; сверьте детали и терминологию с лекцией преподавателя.

### Твёрдые ткани зуба
- **Эмаль** — высокоминерализованная ткань, образованная эмалью амелобластов во время развития зуба; после прорезывания полноценная клеточная регенерация эмали невозможна.
- **Дентин** формируется одонтобластами, тела которых лежат по периферии пульпы; отростки проходят в дентинных канальцах.
- **Цемент** покрывает корень зуба и участвует в прикреплении волокон периодонтальной связки.
- **Пульпа** — рыхлая соединительная ткань с сосудами, нервами и одонтобластическим слоем по периферии.

### Слюнные железы
Околоушная железа преимущественно серозная; поднижнечелюстная — смешанная с преобладанием серозного компонента; подъязычная — смешанная с преобладанием слизистого. При распознавании сравнивайте вид секреторных отделов, просветы протоков и количество жировых клеток (особенно в околоушной железе).

### Слизистая оболочка полости рта
Эпителий зависит от механической нагрузки: в участках жевательной слизистой обычно выражено ороговение, в выстилающей слизистой чаще встречается многослойный плоский неороговевающий эпителий. В губе различают кожную, промежуточную и слизистую зоны; в языке оценивают тип сосочков и наличие вкусовых почек там, где они характерны.

