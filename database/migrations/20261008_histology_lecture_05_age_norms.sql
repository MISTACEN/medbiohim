### 7A. Возрастные нормы гемограммы — временная шкала

> **Важно:** этот блок собран по дополнению к Lecture 05, присланному для занятия. Числа и формулировки сохранены по исходному материалу. Если в нём приведены варианты нормы из разных источников, они показаны как варианты, а не молча сведены к одному числу.

Главная временная шкала для практической карточки — соотношение **нейтрофилов и лимфоцитов**:

| Возраст | Нейтрофилы | Лимфоциты | Кто преобладает |
|---|---:|---:|---|
| Новорождённый, 1-е сутки | 60–70% | 20–30% | Нейтрофилы |
| 4-е сутки — 1-й перекрёст | ≈45% | ≈45% | Равны |
| 1–2 года | 25–30% | 60–65% (до 70%) | Лимфоциты |
| 4 года — 2-й перекрёст | ≈45% | ≈45% | Равны |
| 14–15 лет и взрослые | 47–72% | 19–37% | Нейтрофилы |

**Правило карточки:** сначала смотри возраст, затем выбирай норму, и только после этого оценивай отклонение. Для ребёнка 1–2 лет лимфоциты около 60–65% в присланном материале относятся к физиологической норме.

