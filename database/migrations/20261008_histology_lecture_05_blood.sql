Функции: антипаразитарная защита; инактивация гистамина и участие в аллергических реакциях.

> **Узнавание:** 2 сегмента + крупные розовые гранулы = эозинофил.

### Базофилы — 0,5–1%

Размер 11–12 мкм. Ядро слабодольчатое, S-образное или овальное, часто скрыто крупными метахроматичными гранулами.

Гранулы: **гистамин, гепарин, серотонин, гистидиндекарбоксилаза**.

Функция: аллергические реакции немедленного типа. Гистамин повышает проницаемость сосудов; гепарин снижает свёртываемость.

### Лимфоциты — 19–37%

Круглые клетки с крупным округлым ядром, плотным гетерохроматином и узким ободком базофильной цитоплазмы.

| Группа | Размер | Доля |
|---|---:|---:|
| Малые | <7 мкм | 85–90% |
| Средние | 8–10 мкм | 10–12% |
| Большие | >10 мкм | отсутствуют или единичны |

