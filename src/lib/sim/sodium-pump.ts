/** K₀.₅ насоса по внеклеточному K⁺: типичный диапазон 0.5–2 мМ, берём 1 мМ. */
const KM_K_OUT = 1;

/** Электрогенный вклад насоса при нормокалиемии, мВ (учебная оценка: 5–10 мВ). */
const EM_REFERENCE_MV = -8;

/** Стехиометрия цикла — установленный факт. */
export const PUMP_STOICHIOMETRY = { naOut: 3, kIn: 2, atp: 1 } as const;

export function pumpActivityFactor(kOutMm: number, blockedFraction: number): number {
  const kFactor = kOutMm / (KM_K_OUT + kOutMm);
  return kFactor * (1 - blockedFraction);
}

