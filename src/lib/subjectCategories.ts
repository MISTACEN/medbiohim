/**
 * Категории предметов для каталога /subjects.
 *
 * В таблице `subjects` нет колонки категории, и `/api/v1/subjects-catalog`
 * её не возвращает. Без этого слоя каждый предмет получал «Другое», и вся
 * группировка страницы схлопывалась в один блок.
 *
 * Правила проверяются по порядку: первое совпадение выигрывает. Порядок важен —
 * «Элективные курсы по физической культуре» должны попасть в элективы, а не в
 * естественные науки из-за корня «физик».
 */
export const SUBJECT_CATEGORY_FALLBACK = "Другое";

const RULES: ReadonlyArray<readonly [RegExp, string]> = [
  [/электив|физическ[а-яё]*\s+культур|б1\.в\.дв|не выбрана из набора|практик|выпускная квалификационная/i, "Элективы"],
  [/математич|информатик|информационн|теория вероятност|статистик|электроник|программир/i, "Математика и IT"],
  [
    /хими|физик|биолог|биохим|биофизик|анатом|физиолог|гистолог|цитолог|микробиолог|вирусолог|генетик|иммунолог|фармаколог|токсиколог|радиобиолог|молекулярн|биотехнолог|биоинженер/i,
    "Естественно-научные",
  ],
  [
    /пропедевтик|внутренних болезней|инфекционн|аллерголог|патологическ|патофизиолог|лабораторн|хирург|судебно-медицин|гигиен|общественное здоровье|клиническ|морфологическ|косметолог|медицинские технологии|медицина катастроф|первая медицинская помощь/i,
    "Клинические навыки",
  ],
  [
    /истори|философ|иностранн|латинск|психолог|педагогик|экономик|право|биоэтик|государственност|здравоохран/i,
    "Гуманитарные",
  ],
];

export function subjectCategory(name?: string | null, slug?: string | null): string {
  const haystack = `${name || ""} ${slug || ""}`.trim();
  if (!haystack) return SUBJECT_CATEGORY_FALLBACK;
  for (const [pattern, category] of RULES) {
    if (pattern.test(haystack)) return category;
  }
  return SUBJECT_CATEGORY_FALLBACK;
}
