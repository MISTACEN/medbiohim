Специфические гранулы (80–90%) содержат щелочную фосфатазу, лактоферрин, лизоцим, фагоцитин. Азурофильные (10–20%) — первичные лизосомы с миелопероксидазой, кислой фосфатазой, протеазами.

**Функция:** микрофаги — фагоцитоз бактерий и повреждённых тканей, бактерицидные белки и активные формы кислорода.

**Сдвиг влево** — увеличение юных и палочкоядерных форм; в исходном конспекте связан с острым бактериальным воспалением / гнойным процессом.

### Эозинофилы — 1–6%

Размер 12–14 мкм. **Ядро строго из 2 сегментов («очки»).** Гранулы крупные, оксифильные, ярко-розовые.

