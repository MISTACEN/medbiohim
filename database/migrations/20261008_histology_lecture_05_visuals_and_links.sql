### 16.3. Как работать с фотографией

1. Закрой подпись и назови клетку.
2. Определи размер относительно эритроцита.
3. Посмотри на форму и сегментацию ядра.
4. Оцени зернистость цитоплазмы.
5. Назови 1–2 признака, по которым исключаются ближайшие похожие клетки.
6. Только после этого сверяйся с подписью.

**Связка для практики:** препарат → морфологический признак → функция → электронограмма → тест.
