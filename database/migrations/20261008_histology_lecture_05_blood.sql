## 2. Эритроциты — Erythrocyti

Эритроциты — высокодифференцированные **безъядерные постклеточные структуры**.

| Признак | Характеристика |
|---|---|
| Форма | двояковогнутый диск — дискоцит |
| Диаметр | 7,0–8,0 мкм |
| Толщина на периферии | 2,0–2,5 мкм |
| Толщина в центре | около 1,0 мкм |
| Ядро и органеллы | отсутствуют |
| Вода | около 60% |
| Сухой остаток | около 40% |
| Гемоглобин | около 95% сухого остатка |
| Жизнь | около 120 суток |

### Изменения

**Анизоцитоз** — изменение размеров: микроциты <7,0 мкм, макроциты >8,0 мкм.

**Пойкилоцитоз** — изменение формы: эхиноциты, стоматоциты, сфероциты.

### Мембрана

