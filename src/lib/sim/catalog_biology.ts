function embryoSizeMm(day: number): number {
  const points = EMBRYO_SIZE_POINTS;
  if (day <= points[0][0]) return points[0][1];
  for (let index = 1; index < points.length; index += 1) {
    const [d1, s1] = points[index - 1];
    const [d2, s2] = points[index];
    if (day <= d2) {
      const t = (day - d1) / (d2 - d1);
      return s1 + (s2 - s1) * t;
    }
  }
  return points[points.length - 1][1];
}

