/**
 * Ключ сравнения формулировок вопросов.
 *
 * Импорт методичек приносит один и тот же вопрос дважды: разные id, одинаковый
 * текст, а отличаются они только числом подчёркиваний в пропуске («_____» и
 * «______»), регистром первой буквы или точкой в конце. Для студента это
 * повтор, поэтому при сборке прохождения такие строки склеиваются по ключу.
 */
export function questionTextKey(text) {
  return String(text ?? "")
    .toLowerCase()
    .replace(/[^0-9a-zа-яё]+/g, " ")
    .trim();
}
