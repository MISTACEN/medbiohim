/**
 * Сравнимое название лекции — одно правило для браузера и Worker.
 *
 * Раньше функция была продублирована в `workers/api/src/lib/lecture-quality.ts`
 * (проверка дублей перед публикацией) и в `ArchiveLectures.tsx` (слияние наборов
 * портала), причём правила разошлись: Worker срезал «Неделя 3», клиент — «Тема 2»
 * и «Конспект». Здесь объединение обоих вариантов, поэтому одна и та же лекция
 * распознаётся как одна и там, и там.
 */

/** Сравнимое название: без «Тема 2.», «Неделя 3 · Лекция 3», регистра и пунктуации. */
export function normalizeLectureTitle(value: unknown): string {
  return String(value || "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/^(?:тема|неделя|недели)\s*[\d\s.,–\-—/]*/i, "")
    .replace(/(?:лекция|лекции|конспект|практика|семинар)\s*[\d\s.,–\-—/·:]*/gi, "")
    .replace(/[^a-zа-я0-9]+/gi, " ")
    .trim();
}
