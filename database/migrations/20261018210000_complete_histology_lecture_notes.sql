### Общий план
Сердечно-сосудистая система включает сердце и сосуды. Стенка большинства сосудов образована тремя оболочками: внутренней (интима с эндотелием), средней (гладкие миоциты и/или эластические элементы) и наружной (соединительная ткань). Их выраженность зависит от типа и калибра сосуда.

### Сердце
Эндокард выстилает камеры сердца и включает эндотелий с подлежащей соединительной тканью. Миокард образован поперечно-полосатыми кардиомиоцитами, соединёнными вставочными дисками. Эпикард соответствует висцеральному листку серозного перикарда и содержит мезотелий, соединительную ткань, сосуды и нередко жировую ткань.

### Типы сосудов
- **Артерии эластического типа** (например, аорта): многочисленные эластические мембраны в средней оболочке смягчают пульсовые колебания.
- **Артерии мышечного типа**: хорошо выраженная средняя оболочка с циркулярно расположенными гладкими миоцитами регулирует распределение кровотока.
- **Вены**: стенка обычно тоньше, просвет часто шире и неправильной формы; в некоторых венах имеются клапаны.
- **Капилляры**: эндотелий и базальная мембрана, иногда перициты; основное место обмена между кровью и тканями.

### Признаки на микропрепарате
Сначала определите просвет и эндотелий, затем оцените толщину и состав средней оболочки. У артерии мышечного типа средняя оболочка относительно толстая; у вены обычно тоньше и менее упорядочена. В миокарде ищите ветвящиеся кардиомиоциты, центральные ядра и вставочные диски.
